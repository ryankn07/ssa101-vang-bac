/* SSA101 V10 bundle generator: node tools/build-v10.mjs.
 * Edit separate source files; regenerate bundles and commit the generated assets.
 * The deployed index.html loads only site-v10.css and site-v10.js.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cssSources = ["styles.css","motion.css","typography-mix.css","footer-refresh.css","navigation-v5.css","showcase-v6.css","demo-experience-v7.css","reliability-v8.css"];
const jsSources = ["script.js","calendar-week.js","calendar-switch.js","navigation-v5.js","demo-experience-v7.js","reliability-v8.js"];
async function bundle(paths, dest, kind) {
  const header = '/* SSA101 / Vang Bac - compiled V10 ' + kind + '. AUTO-GENERATED from ordered source files by tools/build-v10.mjs. Do not edit this file directly. */';
  const pieces = [header];
  for (const path of paths) {
    const contents = await readFile(join(root, path), 'utf8');
    pieces.push((kind === 'JavaScript' ? '\n;/* SOURCE: ' : '\n/* SOURCE: ') + path + ' */\n' + contents);
  }
  const result = pieces.join('\n') + '\n';
  await writeFile(join(root, dest), result, 'utf8');
  console.log(dest + ': ' + Buffer.byteLength(result) + ' bytes from ' + paths.length + ' source files');
}
await bundle(cssSources, 'site-v10.css', 'CSS');
await bundle(jsSources, 'site-v10.js', 'JavaScript');
